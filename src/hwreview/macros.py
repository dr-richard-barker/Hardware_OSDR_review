"""Write results/macros.tex: every number quoted in the manuscript, generated from results.

The manuscript never types a result; it uses \\hw<Name> macros defined here, so a
re-run of the pipeline updates the text. Run after all analysis stages.
"""
from __future__ import annotations

import json
import re

import pandas as pd

from . import sources
from .paths import CURATED, ROOT, TABLES


def _name(s: str) -> str:
    s = re.sub(r"[^A-Za-z]", " ", s).title().replace(" ", "")
    return "hw" + s


def fmt(v, nd=2):
    if isinstance(v, (int,)) or (isinstance(v, float) and v.is_integer() and abs(v) >= 10):
        return f"{int(v):,}".replace(",", "{,}")
    if isinstance(v, float):
        if v != 0 and (abs(v) < 1e-3 or abs(v) >= 1e5):
            m, e = f"{v:.1e}".split("e")
            return f"{m}\\times10^{{{int(e)}}}"
        return f"{v:.{nd}f}"
    return str(v)


def run():
    M = {}
    n = pd.read_csv(TABLES / "T2_counts.csv")
    c = {(g, k): v for g, k, v in n[["group", "key", "n"]].values}
    M["NEntities"] = c[("total", "hardware entities")]
    M["NSplash"] = c[("total", "in SPLASH")]
    M["NRegistry"] = c[("total", "in OSDR registry")]
    M["NPlatformNamed"] = c[("total", "named by >=1 OSD study platform field")]
    M["NLinkedStudy"] = c[("total", "linked to >=1 OSD study (any route)")]
    M["NBioCapable"] = c[("bio", "bio-payload capable")]
    M["NHabitats"] = c[("bio", "specimen habitats (live specimens housed in flight)")]
    M["NBioWithStudy"] = c[("bio", "bio-capable with >=1 OSD study")]
    for k in ("agar_gel", "arcillite_substrate", "hydroponic_aeroponic", "liquid_culture_medium",
              "animal_food_water", "aquatic_water_loop", "water_only_wick", "none evidenced"):
        M["NNut" + _name(k)[2:]] = c.get(("nutrient mode (habitats)", k), 0)
    for (g, k), v in c.items():
        if g == "platform (missions, bio-capable)":
            M["NPlat" + _name(k)[2:]] = v
        if g == "role":
            M["NRole" + _name(k)[2:]] = v
    s = json.loads((TABLES / "T4_summary.json").read_text())
    M["NHabUsed"] = s["n_used"]
    M["ComplMedianPublic"] = s["completeness_median_public"]
    M["ComplMedianSplash"] = s["completeness_median_splash"]
    M["RhoUse"] = s["spearman_studies_completeness_all"]["rho"]
    M["PUse"] = s["spearman_studies_completeness_all"]["p"]
    for t in s["tests"]:
        nm = _name(t["factor"])[2:]
        if "p" in t:
            M[f"KW{nm}P"] = t["p"]
            M[f"KW{nm}H"] = t["H"]
            M[f"KW{nm}N"] = t["n"]
    ts = s["tier_sensitivity"]
    for scope, d in ts.items():
        for tier in "ABC":
            M[f"Tier{_name(scope)[2:]}{tier}"] = d.get(tier, 0)
    d = s["integrity_defects"]
    M["NDatasets"] = d["osdr_datasets"]
    M["NDatasetsNoPlatform"] = d["osdr_datasets_without_platform"]
    M["NPlatformStrings"] = d["distinct_platform_strings"]
    M["NVeggieSpellings"] = d["veggie_spellings"]
    M["NPlatformNotHardware"] = d["platform_components_not_hardware"]
    cls = pd.read_json(ROOT / "data" / "derived" / "classification.json")
    sgc = cls[cls.registry_ids.map(lambda v: "2052" in [str(x) for x in v])]
    M["NCatchallStudies"] = int(sgc.n_osd_studies.iloc[0]) if len(sgc) else 0
    rev = pd.read_csv(CURATED / "splash_field_review.csv")
    M["NSplashMisattributed"] = int((rev.verdict == "misattributed").sum())
    M["NSplashUncertain"] = int((rev.verdict == "uncertain").sum())
    sp = sources.splash()
    M["NSplashBlock"] = int(((sp.index >= 121) & (sp.index <= 147)).sum())
    v = json.loads((TABLES / "T5_scorer_validation.json").read_text())
    M["ValRaterExact"] = 100 * v["rater_exact_agreement"]
    M["ValRaterKappa"] = v["rater_weighted_kappa"]
    M["ValAutoExact"] = 100 * v["auto_exact_agreement"]
    M["ValAutoKappa"] = v["auto_weighted_kappa"]
    M["ValPrecision"] = v["auto_presence_precision"]
    M["ValRecall"] = v["auto_presence_recall"]
    M["ValRho"] = v["entity_completeness_spearman"]
    M["ValGoldMean"] = v["entity_completeness_mean_gold"]
    M["ValAutoMean"] = v["entity_completeness_mean_auto"]
    it = pd.read_csv(TABLES / "T4c_item_missingness.csv").set_index("item")
    for k in it.index:
        M[f"Item{k}Quant"] = 100 * it.loc[k, "quantitative"]
        M[f"Item{k}Absent"] = 100 * it.loc[k, "absent"]
        M[f"Item{k}SplashQuant"] = 100 * it.loc[k, "splash_quantitative"]
    for vf in sorted(TABLES.glob("V_verification_cavity_Ra*.json")):
        for r in json.loads(vf.read_text())["cavity"]:
            ra = {1e4: "Four", 1e5: "Five", 1e6: "Six"}[r["Ra"]]
            M[f"NuRa{ra}N{r['n']}"] = r["Nu"]
            M[f"NuErrRa{ra}N{r['n']}"] = r["err_vs_Hortmann_pct"]
    lines = ["% Generated by hwreview.macros - do not edit by hand.\n"]
    # --- literature curation and audit
    t6 = pd.read_csv(TABLES / "T6_curated_tiers.csv")
    M["NCurated"] = len(t6)
    M["NCuratedA"] = int((t6.tier == "A").sum())
    M["NCuratedB"] = int((t6.tier == "B").sum())
    M["NCuratedC"] = int((t6.tier == "C").sum())
    M["NCuratedParams"] = int(t6.n_parameters.sum())
    M["NCuratedSourced"] = int(t6.n_sourced.sum())
    M["PctCuratedSourced"] = 100 * t6.n_sourced.sum() / t6.n_parameters.sum()
    M["NMissingFTwo"] = int((~t6.F2.astype(bool)).sum())
    M["NMissingGOne"] = int((~t6.G1.astype(bool)).sum())
    M["NMissingGTwo"] = int((~t6.G2.astype(bool)).sum())
    qa = CURATED / "quote_audit_results.csv"
    if qa.exists():
        q = pd.read_csv(qa)
        M["NAudit"] = len(q)
        M["NAuditQuoteFound"] = int((q.quote_found == "yes").sum())
        M["NAuditValueYes"] = int((q.value_supported == "yes").sum())
        M["NAuditValuePartial"] = int((q.value_supported == "partial").sum())
        M["NAuditValueNo"] = int((q.value_supported == "no").sum())
    # --- verification
    t8 = TABLES / "T8_verification_cavity.csv"
    if t8.exists():
        v = pd.read_csv(t8).set_index("Ra")
        for ra, nm in ((1e4, "Four"), (1e5, "Five"), (1e6, "Six")):
            if ra in v.index:
                M[f"VerPRa{nm}"] = v.loc[ra, "p_observed"]
                M[f"VerExtErrRa{nm}"] = abs(v.loc[ra, "err_ext_vs_Hortmann_pct"])
                M[f"VerFineErrRa{nm}"] = abs(v.loc[ra, "err_fine_vs_Hortmann_pct"])
        M["VerMaxExtErr"] = v.err_ext_vs_Hortmann_pct.abs().max()
    t8b = TABLES / "T8b_verification_diffusion.csv"
    if t8b.exists():
        M["VerDiffMaxErr"] = pd.read_csv(t8b).max_abs_err.max()
    # --- GCI and CFD results
    t7 = TABLES / "T7_gci.csv"
    if t7.exists():
        g = pd.read_csv(t7)
        g = g[g.gci_fine_pct.notna()]
        M["GciMax"] = g.gci_fine_pct.max()
        M["GciMedian"] = g.gci_fine_pct.median()
        M["NGciQuantities"] = len(g)
        M["NGciMonotonic"] = int((g.convergence == "monotonic").sum())
    t9 = TABLES / "T9_cfd_results_medium.csv"
    if t9.exists():
        r = pd.read_csv(t9)
        M["CfdMaxImbalance"] = 100 * r.CO2_balance_rel_imbalance.abs().max()
        if "Re_inlet" in r:
            lam = r[r.model != "aph_fanmax"]
            M["CfdMaxReInletLaminar"] = lam.Re_inlet.max()
            if (r.model == "aph_fanmax").any():
                M["CfdReInletFanmax"] = r[r.model == "aph_fanmax"].Re_inlet.max()
        short = {"aph": "Aph", "aph_fanmax": "AphFanmax", "mds": "Mds", "vented_fly_box_vent20": "VfbSmall",
                 "vented_fly_box_vent60": "VfbLarge", "aqh": "Aqh"}
        for _, x in r.iterrows():
            k = short.get(x.model, x.model) + ("Zero" if x.gravity == "0g" else "One")
            for col, nm in (("CO2_excess_ppm", "Co"), ("T_excess_K", "Dt"), ("age_of_air_s", "Age"),
                            ("H2O_excess_mmol_mol", "Ht"), ("U_max_m_s", "Umax"), ("Re", "Re"), ("Ri_1g", "Ri")):
                if pd.notna(x[col]):
                    M[f"Cfd{k}{nm}"] = float(x[col])
    words = dict(zip("0123456789", ["Zero", "One", "Two", "Three", "Four", "Five", "Six", "Seven", "Eight",
                                    "Nine"]))
    seen = {}
    for k, val in sorted(M.items()):
        nm = "hw" + re.sub(r"[^A-Za-z]", "", "".join(words.get(ch, ch) for ch in k))
        if nm in seen:
            raise ValueError(f"macro name collision: {k} and {seen[nm]} -> {nm}")
        seen[nm] = k
        lines.append(f"\\newcommand{{\\{nm}}}{{{fmt(val)}}}\n")
    out = ROOT / "results" / "macros.tex"
    out.write_text("".join(lines))
    return M


if __name__ == "__main__":
    m = run()
    print(len(m), "macros")
